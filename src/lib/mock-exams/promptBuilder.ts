function getMixedStyleInstruction(profName: string, questionCount: number): string {
    return `
نمط الأسئلة المطلوب: مختلط ومتنوع بذكاء قياسي (Mixed Cognitive Styles)
يجب تنويع صياغة الأسئلة الـ ${questionCount} بشكل متوازن بين الأنماط المهنية التخصصية التالية لمهنة "${profName}":
1. تعريف مصطلحات ومفاهيم فنية دقيقة (DEFINITION)
2. قيم وأرقام تشغيلية ومعايير قياسية (VALUES_NUMBERS)
3. معايير وكودات ومواصفات معتمدة (STANDARDS)
4. تحديد الأدوات وأجهزة الفحص التخصصية (TOOL_IDENTIFICATION)
5. إجراءات السلامة وتقييم المخاطر الميدانية (SAFETY)
6. ترتيب وتسلسل خطوات العمل القياسية (STEP_ORDER)
7. مقارنة وتمييز فني بين الطرق أو المواد (COMPARISON)
8. كشف المخالفات والأخطاء الفنية (ERROR_IDENTIFICATION)
9. أفضل الممارسات المعيارية المعتمدة (BEST_PRACTICE)
10. سيناريوهات ميدانية واقعية وتشخيص أعطال (SCENARIO_SHORT / SCENARIO_COMPLEX)
11. حسابات وتحويلات فنية هندسية (CALCULATION)
12. السبب والنتيجة وتشخيص الظواهر (CAUSE_EFFECT)

يجب تحديد النمط المستخدم فعلياً في حقل "questionStyle" لكل سؤال من القيم المعتمدة حصراً.`;
}

