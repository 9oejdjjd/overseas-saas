function buildCognitiveTaxonomyInstructions(diffs: string[]): string {
    const lines: string[] = [];

    lines.push(`
══════════════════════════════════════════════════════════════════════════════════
📊 مصفوفة المستويات المعرفية ودرجات الصعوبة المعتمدة (K1 - K5 Cognitive Taxonomy):
══════════════════════════════════════════════════════════════════════════════════
يجب الالتزام الحرفي بالتعريف والمعيار والمستوى المحدد في كل سؤال بحسب المستوى المعرفي المطلوب:`);

    if (diffs.includes("K1")) {
        lines.push(`
■ مستوى K1 (معرفة واستدعاء مباشر - صعوبة عالية جداً / مستوى خبير):
- الهدف والقياس: يقيس استدعاء المصطلحات الفنية، الرموز، النسب، والمعايير القياسية المباشرة، بصيغة دقيقة وشديدة الصعوبة تفرّق بين الممارس العادي والخبير.
- طبيعة السؤال: سؤال فني مركز وصريح، يخلو من الحشو القصصي، ويختبر معرفة تخصصية عميقة بالمهنة.
- جودة الخيارات: جميع الخيارات تبدو مقبولة ظاهرياً ولكن خياراً واحداً فقط هو الأصح مهنياً وقانونياً.
- حقول الـ JSON الإلزامية: "cognitiveLevel": "K1"، "difficulty": "HARD".`);
    }

    if (diffs.includes("K2") || diffs.includes("HARD")) {
        lines.push(`
■ مستوى K2 (تطبيق وتشغيل - صعوبة عالية جداً / مستوى خبير):
- الهدف والقياس: يقيس التطبيق المباشر للقواعد والإجراءات في ظروف العمل والتشغيل الميداني المعتادة بصياغة عميقة وصعبة.
- طبيعة السؤال: سيناريو مهني تطبيقي من بيئة العمل (3-4 أسطر) يختبر تنفيذ الإجراءات المعيارية والتعامل مع المعدات.
- جودة الخيارات: جميع الخيارات تبدو مقبولة ظاهرياً ولكن خياراً واحداً فقط هو الأصح مهنياً وقانونياً وميدانياً.
- حقول الـ JSON الإلزامية: "cognitiveLevel": "K2"، "difficulty": "HARD".`);
    }

    if (diffs.includes("K3") || diffs.includes("EXPERT")) {
        lines.push(`
■ مستوى K3 (تحليل ومقارنة - صعوبة عالية جداً / مستوى خبير واستشاري):
- الهدف والقياس: يقيس تشخيص أسباب المشاكل الميدانية، حل المشكلات، والمقارنة بين إجراءين في حالات غير اعتيادية أو سيناريوهات معقدة.
- طبيعة السؤال: سيناريو فني معقد متعدد العوامل (5-7 أسطر) يختبر القدرة على التحليل العميق والمفاضلة بين بدائل تخصصية.
- جودة الخيارات: جميع الخيارات تبدو مقبولة وصحيحة جزئياً ولكن خياراً واحداً فقط هو الأصح والأشمل مهنياً وقانونياً.
- حقول الـ JSON الإلزامية: "cognitiveLevel": "K3"، "difficulty": "EXPERT".`);
    }

    if (diffs.includes("K4")) {
        lines.push(`
■ مستوى K4 (حل مشكلات وتشخيص أعطال - درجة صعوبة: من متوسط إلى صعب):
- الهدف والقياس: يقيس استكشاف الأخطاء الفنية وتصحيحها عبر سيناريوهات متوسطة التعقيد وبدرجة صعوبة متدرجة (من متوسط إلى صعب).
- طبيعة السؤال: سيناريو يصف عطلاً أو خللاً تشغيلياً ويطلب تشخيص السبب المؤدي إليه أو تحديد مسار الفحص والعلاج الفني.
- جودة الخيارات: جميع الخيارات تبدو مقبولة ظاهرياً ولكن خياراً واحداً فقط هو الأصح مهنياً وقانونياً.
- حقول الـ JSON الإلزامية: "cognitiveLevel": "K4"، "difficulty": "HARD".`);
    }

    if (diffs.includes("K5")) {
        lines.push(`
■ مستوى K5 (تقييم واتخاذ قرار - درجة صعوبة: من سهل إلى متوسط):
- الهدف والقياس: يقيس التقييم الأساسي لاتخاذ القرارات الميدانية بصياغة واضحة ومباشرة وبدرجة صعوبة خفيفة (من سهل إلى متوسط).
- طبيعة السؤال: موقف مهني أساسي وواضح يتطلب اتخاذ القرار المهني السليم وتحديد الخطوة التالية في بيئة العمل.
- جودة الخيارات: جميع الخيارات تبدو مقبولة ظاهرياً ولكن خياراً واحداً فقط هو الأصح مهنياً وقانونياً.
- حقول الـ JSON الإلزامية: "cognitiveLevel": "K5"، "difficulty": "HARD".`);
    }

    return lines.join("\n");
}

